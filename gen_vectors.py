"""gen_vectors.py — write Vectors.lean from vectors/vectors.json (B3 cases only), the exact test vectors
shipped with bristorbrot's bristor_product code block (CC0).

The parity control: Bristor.lean's `mul` must reproduce the exact expectations that
export_conv_vectors.py computed from the one-line rule alone, on the same file every port answers to.
Inputs are multiples of 1/8, so everything is scaled by 8 into ℤ (products and squares by 64);
that scaling is valid because `mul` is bilinear (Bristor.lean `mul_smul_left/right`).

Also writes plant_vec.lean: canon `mul` claimed equal to the j_roll column on the first case where the
columns differ. It must FAIL; if it passes, the vector check cannot tell the rolls apart.

usage: gen_vectors.py <vectors.json> <outdir>
"""
import json
import os
import sys
from fractions import Fraction


def scaled(vals, k):
    out = []
    for v in vals:
        f = Fraction(v).limit_denominator(1 << 20) * k
        if f.denominator != 1 or Fraction(v) * k != f:
            raise SystemExit(f"gen_vectors: {v} * {k} is not an exact integer")
        out.append(int(f))
    return out


def lit(xs):
    return "(⟨" + ", ".join(f"({x})" for x in xs) + "⟩ : B3 Int)"


def main():
    src, outdir = sys.argv[1], sys.argv[2]
    V = json.load(open(src))
    lines, plant = [], None
    nprod = nsq = 0
    for c in V["product"]:
        if c["n"] != 3:
            continue
        a, b, canon = scaled(c["a"], 8), scaled(c["b"], 8), scaled(c["canon"], 64)
        lines.append(f"-- product {c.get('label', '')}\nexample : B3.mul {lit(a)} {lit(b)} = {lit(canon)} := by decide")
        nprod += 1
        if plant is None and c["j_roll"] != c["canon"]:
            plant = (c.get("label", ""), a, b, scaled(c["j_roll"], 64))
    for c in V["square"]:
        if c["n"] != 3:
            continue
        z, canon = scaled(c["z"], 8), scaled(c["canon"], 64)
        lines.append(f"-- square\nexample : B3.mul {lit(z)} {lit(z)} = {lit(canon)} := by decide")
        nsq += 1
    open(f"{outdir}/vectors_body.lean", "w").write(
        f"/-! generated by gen_vectors.py from {os.path.basename(src)}: {nprod} B3 products, {nsq} B3 squares -/\n"
        + "\n".join(lines) + "\n")
    if plant is None:
        raise SystemExit("gen_vectors: no B3 product case separates canon from j_roll — plant cannot be built")
    lab, a, b, jr = plant
    open(f"{outdir}/plant_vec.lean", "w").write(
        f"-- PLANT (must fail): canon mul claimed equal to the j_roll column, case {lab}\n"
        f"example : B3.mul {lit(a)} {lit(b)} = {lit(jr)} := by decide\n")
    print(f"vectors: {nprod} products + {nsq} squares (n=3); plant_vec on case {lab}")


if __name__ == "__main__":
    main()
